create or replace function private.ncreate_protect_topic_fields()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if (select auth.uid()) is not null
    and not private.is_staff((select auth.uid()))
    and (
      new.category_id is distinct from old.category_id
      or new.author_id is distinct from old.author_id
      or new.slug is distinct from old.slug
      or new.is_pinned is distinct from old.is_pinned
      or new.is_locked is distinct from old.is_locked
      or new.deleted_at is distinct from old.deleted_at
      or new.deleted_by is distinct from old.deleted_by
      or new.deletion_reason is distinct from old.deletion_reason
    )
  then
    raise exception 'Only NCreate staff can change topic moderation fields'
      using errcode = '42501';
  end if;
  return new;
end;
$$;

