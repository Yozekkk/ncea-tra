create or replace function public.create_ncreate_forum_topic(
  _category_id bigint,
  _title text,
  _slug text,
  _body text
)
returns uuid
language plpgsql
security invoker
set search_path = ''
as $$
declare
  created_topic_id uuid;
begin
  if (select auth.uid()) is null then
    raise exception 'authentication_required' using errcode = '42501';
  end if;
  if char_length(btrim(_title)) not between 3 and 180 then
    raise exception 'invalid_topic_title' using errcode = '22023';
  end if;
  if char_length(btrim(_body)) not between 1 and 20000 then
    raise exception 'invalid_topic_body' using errcode = '22023';
  end if;
  if _slug !~ '^[a-z0-9]+(?:-[a-z0-9]+)*-[0-9a-f]{8}$' then
    raise exception 'invalid_topic_slug' using errcode = '22023';
  end if;

  insert into public.ncreate_forum_topics (category_id, author_id, title, slug)
  values (_category_id, (select auth.uid()), btrim(_title), _slug)
  returning id into created_topic_id;

  insert into public.ncreate_forum_posts (topic_id, author_id, body)
  values (created_topic_id, (select auth.uid()), btrim(_body));

  return created_topic_id;
end;
$$;

create or replace function public.create_ncreate_forum_reply(_topic_id uuid, _body text)
returns uuid
language plpgsql
security invoker
set search_path = ''
as $$
declare
  created_post_id uuid;
begin
  if (select auth.uid()) is null then
    raise exception 'authentication_required' using errcode = '42501';
  end if;
  if char_length(btrim(_body)) not between 1 and 20000 then
    raise exception 'invalid_reply_body' using errcode = '22023';
  end if;

  insert into public.ncreate_forum_posts (topic_id, author_id, body)
  values (_topic_id, (select auth.uid()), btrim(_body))
  returning id into created_post_id;

  return created_post_id;
end;
$$;

